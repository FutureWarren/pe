"""成交后加微信的那一刻：把客户接进能被 AI 服务的通道。

## 这是整套方案的支点

酷机时代的主要客流是**线下**：客户到店买了手机，**成交之后**销售让他加微信，
后续的售后咨询全走这个微信。一个月几万客户，绝大多数是这么来的。

而客户加的是**销售/门店的企业微信**（外部联系人），这条通道上——
已核腾讯官方文档——**服务端没有任何接口能代替员工发一条任意消息**。
企业群发要员工在客户端逐条点确认，每客户每月还限约 30 条。

所以「AI 直接代客服回复」在这条通道上做不到。**除了一个例外：**

> `externalcontact/send_welcome_msg`（新客户欢迎语）是客户联系通道里
> **唯一一个服务端全自动下发、内容完全任意、不需要任何人点确认**的接口。
> 它的触发时机恰好就是「客户刚把销售加上」的那一秒。

**而那一秒正是我们要的那一秒。** 客户刚成交、刚加上微信，注意力还在，
这时候递给他一张「售后专属客服」的名片，是所有引流时机里转化最高的一个——
因为它不是打扰，是服务的一部分。

    客户到店成交
      → 销售让他加企业微信
      → 触发「添加外部联系人」回调
      → 我们在 20 秒内调 send_welcome_msg
      → 发一条带订单信息的欢迎语 + 售后客服入口
      → 客户点进去 = 微信客服会话
      → **从此售后全部由 AI 自动接待**（见 docs/retail-kuji.md 通道一节）

一次性把人接过去，之后几个月的售后咨询就都在 AI 能说话的地方了。

## 20 秒是硬窗口

企微在「添加外部联系人」回调里给一个 `welcome_code`，**20 秒内不用就作废，
且每个客户只能成功下发一次**。所以这条路径必须：

- **同步发，不进队列。** 排队等后台线程轮到它，20 秒早过了；
- **不调模型。** 一次模型调用最坏要十几秒，赌不起。文案用模板 + 订单字段拼，
  确定性、零延迟（这与律所侧「紧急话术不进模型」是同一条理由）；
- **失败要留痕。** 这一枪只有一次机会，没打响必须有人知道
  （落运维小记，第二天的战报里能看见）。

## 一条必须提前告知门店的配置

**企微管理后台不要给这些成员配欢迎语。** 后台配了的话，回调里就不返回
`welcome_code`，我们这条永远发不出去——而且现象是「什么都没发生」，
不报错、不告警。这正是本项目最怕的那类静默失败，所以写在这里，
也写进 `docs/retail-kuji.md` 的开通清单。
"""

import re
from dataclasses import dataclass


@dataclass(frozen=True)
class WelcomePlan:
    """这一刻要发什么。"""

    text: str
    with_kf_entry: bool         # 是否附带售后客服入口
    reason: str = ""

    @property
    def ok(self) -> bool:
        return bool(self.text.strip())


# 门店成交后加微信，客户此刻的心理状态：刚花了几千块，手里是台新机器。
# 他最关心的三件事按顺序是：机器没问题吧 / 出问题找谁 / 怎么用。
# 所以欢迎语就答这三件，**一句废话都不要**——
# 「感谢您选择我们，我们将竭诚为您服务」这种话等于没说，还占位置。
_BASE = (
    "{name}您好，我是{store}的售后客服。\n"
    "您今天买的{item}已经在我们系统里登记好了，保修从今天开始算。\n"
    "以后想查订单、问保修、约贴膜、或者手机有任何用不明白的地方，"
    "直接在这儿问就行，随时有人回。"
)

_NO_ITEM = (
    "{name}您好，我是{store}的售后客服。\n"
    "您的购机信息已经登记好了，保修从购机当天开始算。\n"
    "以后想查订单、问保修、约贴膜，或者手机有任何用不明白的地方，"
    "直接在这儿问就行，随时有人回。"
)

# 引流到微信客服那一句。刻意说成「专门的售后号」而不是「机器人/智能客服」——
# 客户要的是「有人管我」，而不是「你们给我配了个机器人」。
_KF_ENTRY = (
    "\n另外这是我们的售后专属客服，晚上和周末也有人在，"
    "您点一下加上，以后有事随时找得到人：{kf_link}"
)


def _clean(s: str) -> str:
    """姓名/商品名里可能混进换行、多余空格、以及模板占位符残留。"""
    return re.sub(r"\s+", " ", (s or "").strip())


def build(
    *,
    customer_name: str = "",
    store_name: str = "",
    item: str = "",
    kf_link: str = "",
) -> WelcomePlan:
    """拼出这一刻要发的那条欢迎语。

    **全部由确定性模板 + 已知字段拼成，不调模型。** 20 秒窗口赌不起一次
    十几秒的模型调用；而且这条话里带着订单信息，模型改写只会增加说错的机会。

    `kf_link`：微信客服的接待链接（`kf/add_contact_way` 拿到的那个）。
      没配就不带这一句——**宁可不引流，也不能发一句「点这里」却没有链接**。
    """
    name = _clean(customer_name)
    store = _clean(store_name) or "我们"
    goods = _clean(item)
    link = _clean(kf_link)

    body = (_BASE if goods else _NO_ITEM).format(
        name=name, store=store, item=goods,
    )
    # 没名字时开头会多一个空格，收掉
    body = body.lstrip()

    if link:
        body += _KF_ENTRY.format(kf_link=link)
        return WelcomePlan(body, True, "成交后加微信：欢迎语 + 售后客服入口")
    return WelcomePlan(
        body, False,
        "成交后加微信：欢迎语（未配微信客服链接，本次不引流）",
    )


# 企微返回的、与这条路径相关的错误码。**每一个都要能说清「现在该做什么」**，
# 因为这一枪每个客户只有一次机会，打不响必须当场知道原因。
WELCOME_ERR: dict[int, str] = {
    41051: "这个客户的欢迎语已经发过了（每人只能一次），本次跳过即可，不是故障。",
    41096: (
        "有别的应用抢先发了欢迎语（多应用并发时只有最先调用的那个成功）。"
        "去管理后台看看是不是还有另一个自建应用/第三方应用也在监听这个事件。"
    ),
    40096: "welcome_code 已失效——多半是超过了 20 秒的窗口。检查回调处理是不是被排队拖慢了。",
}


def err_hint(code: int | None) -> str:
    try:
        return WELCOME_ERR.get(int(code), "") if code is not None else ""
    except (TypeError, ValueError):
        return ""


def why_no_code() -> str:
    """回调里压根没给 welcome_code 时，要显示给运维的那句话。

    **这是本路径最容易踩、且最安静的一个坑**：管理后台给成员配了欢迎语，
    企微就不再给我们 welcome_code。现象是「什么都没发生」——
    不报错、不告警、日志里也看不出异常，而每一个新客户都在悄悄流失掉。
    """
    return (
        "企微没有返回 welcome_code，所以这条欢迎语发不出去。"
        "最常见的原因是**管理后台已经给这位成员配置了欢迎语**——"
        "后台配了，接口这条就永远拿不到 code。"
        "去「客户与上下游 → 客户联系 → 欢迎语」把该成员的后台欢迎语关掉，"
        "改由本系统统一发（这样才能带上订单信息和售后客服入口）。"
    )
