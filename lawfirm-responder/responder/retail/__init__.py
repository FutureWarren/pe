"""零售行业包：把这套系统从律所搬到手机零售（酷机时代）。

## 为什么是新目录，而不是改 `engine/rules.py`

**两个行业的目标函数是反的**，这不是词表差异，是设计方向的差异：

|            | 律所                     | 手机零售                       |
|------------|--------------------------|--------------------------------|
| 成功       | 客户被真人接住           | 客户**不用**真人就搞定         |
| 转人工     | 目标（应转尽转）         | 成本，能不转就不转             |
| AI 的本分  | 问清楚、别乱答           | **直接答准**，答不准才叫人     |
| 答错的代价 | 合规风险                 | **真金白银赔钱**（报错价格）   |

把这两套逻辑塞进同一个 `classify()` 里，等于让一个函数同时朝两个方向优化——
每加一条零售规则都要回头验一遍不会误伤律所那 853 条测试。所以零售自成一包，
律所那条路径**一行不动**，由 `Settings.industry` 决定走哪边。

## 这一包里有什么

- `intents.py`  —— 售前 10 类 + 售后 12 类意图识别（纯规则，可测可解释）
- `catalog.py`  —— 商品 / 价格 / 库存数据源。**铁律：数字只能从这里出**
- `orders.py`   —— 订单与售后工单查询
- `standin.py`  —— **AI 补位**：客服来不及回时，AI 顶上还是等人（本包的核心）
- `templates.py`—— 零售话术

## 一条贯穿全包的铁律

律所那边有一条：「手机号必须正则提取，**绝不经模型**——模型抄错一位数字，
律师就打不通电话。」零售把同一条哲学套在钱上，而且更硬：

> **价格、库存、优惠、尾款、抵扣价，一个数字都不许模型生成。**

模型只负责把 `catalog` 查出来的数字组织成人话。报错一个价是要按报价履约或者
赔付的，不是「打不通电话」那种可以补救的错。落地见 `catalog.assert_no_free_numbers`。
"""
