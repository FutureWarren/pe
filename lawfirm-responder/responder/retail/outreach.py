"""主动触达的红线：什么话不许通过微信客服通道发出去。

## 为什么需要这一层

零售最容易起的一个念头是：「48 小时内能发 5 条，那正好用来推新品、推活动、
提醒客户来复购」。**这条路是封的。**

《微信客服功能服务条款》3.3.3：

> 不得通过客服账号发送与客服咨询无关的，如频繁营销、骚扰、侮辱等信息。

也就是说「48 小时 / 5 条」只是**技术上限**，不是许可范围。
落在窗口内的营销推送照样违反条款。而违反条款的后果不是少发一条，
是客服账号被限制——**整条通道一起没**，包括那些正经的售后答复。

这跟律所侧那条护栏是同一种东西：合规不是可选项，
也不是「先做了再说、出事再改」的那类事。

## 判据：这句话是不是在回答客户的问题

允许：客户问了，我们答（无论 AI 还是真人）。
允许：客户的订单发生了他会关心的变化（发货、到店、修好了）——
      这属于服务性通知，不是营销。
**不允许**：他没问，我们主动推销。哪怕包装成「专属福利」。

灰区一律按不允许处理。这一层刻意写得严，因为**赌错的代价是整条通道**。
"""

import re
from dataclasses import dataclass

# 营销话术的典型特征。写宽一点没关系——这一层拦下来的东西，
# 本来就该由销售用他自己的号去发，而不是走客服通道。
_MARKETING = re.compile(
    r"(限时|抢购|秒杀|特价|大促|钜惠|巨惠|清仓|甩卖|"
    r"新品(上市|发布|首发).{0,8}(欢迎|快来|抢|订)|"
    r"(专属|独家|内部).{0,4}(福利|优惠|价格|名额)|"
    r"(最后|仅剩|还有).{0,6}(名额|台|天|小时)|"
    r"(欢迎|快来|赶紧|抓紧).{0,6}(选购|抢购|下单|咨询|了解)|"
    r"点击(领取|查看|了解)|扫码(领|抢|参与)|"
    r"办理|开通.{0,4}(套餐|业务)|"
    r"回馈老客户|感恩回馈|周年庆)"
)

# 服务性通知：客户会关心的、与他自己那笔交易直接相关的变化。这些不算营销。
_SERVICE_NOTICE = re.compile(
    r"(已发货|发出|到货|到店|可以来取|取货|已签收|"
    r"修好|维修完成|检测完成|配件到了|"
    r"发票(已开|开好)|退款(已|到账)|订单)"
)


@dataclass(frozen=True)
class Verdict:
    allowed: bool
    reason: str = ""


def check_outbound(text: str, *, replying_to_customer: bool) -> Verdict:
    """这条要发出去的话，能不能走微信客服通道。

    `replying_to_customer`：这是不是在回答客户刚问的问题。
      是 → 天然合规（就是客服咨询本身），只做一道兜底检查；
      否 → 主动触达，必须是服务性通知，否则一律拦下。
    """
    t = (text or "").strip()
    if not t:
        return Verdict(False, "空内容")

    if replying_to_customer:
        # 即使是在答客户，也不许顺手夹带一段促销——
        # 「您的货明天到，另外我们店庆最后三天欢迎来抢购」这种最常见。
        if _MARKETING.search(t):
            return Verdict(
                False,
                "回复里夹带了营销内容。客服通道只能回答客户问的事，"
                "促销请让销售用自己的企微号发（条款 3.3.3）。",
            )
        return Verdict(True)

    # 主动触达
    if _MARKETING.search(t):
        return Verdict(
            False,
            "这是营销推送，不能走客服通道。《微信客服功能服务条款》3.3.3 "
            "明确禁止发送与客服咨询无关的营销信息——"
            "「48 小时 5 条」是技术上限，不是许可范围。"
            "**违规的代价是整个客服账号被限制，包括正经的售后答复。**",
        )
    if _SERVICE_NOTICE.search(t):
        return Verdict(True)
    return Verdict(
        False,
        "主动触达只允许发与客户自己那笔交易直接相关的服务性通知"
        "（发货、到店、修好、发票、退款）。这条看不出属于哪一类，"
        "灰区一律按不允许处理——赌错的代价是整条通道。",
    )
