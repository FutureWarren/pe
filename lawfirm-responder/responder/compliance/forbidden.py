"""禁止事项清单——硬编码，不依赖模型自觉。

任何将要发出的 AI 回复必须通过 check() 零命中。
清单改动必须人工审核后合并（见 CLAUDE.md 协作约定）。
"""

import re

# (规则名, 模式) —— 命中即拦截
FORBIDDEN: list[tuple[str, str]] = [
    # 承诺结果 / 预测本案
    ("promise-outcome", r"(肯定|一定|保证|包|稳|百分之百|绝对)(能)?(赢|胜诉|没事|判缓|无罪|拿到)"),
    ("promise-outcome", r"(胜诉率|赢面).{0,6}(很高|极高|百分之[六七八九]|9[0-9]%|[89][0-9]%)"),
    ("predict-case",
     r"(你|您)(的|这个)?(案子|案件).{0,12}(会判|能判|肯定|大概率|应该(能|会)(赢|判))"),
    ("predict-case", r"(预计|预测).{0,8}(判|赔|获刑)"),
    # 报价 / 改价（AI 不得提任何具体金额）
    #
    # **金额规则必须同时认中文数字。** 这曾是整道闸门最大的一个洞：
    # 规则只认阿拉伯数字，而 prompts.ANSWER_SYSTEM 又明令模型「数字用中文说」——
    # 系统提示直接把模型推进了闸门的盲区。于是「我们一般收标的额的百分之十到二十」
    # 「赔偿大概三万块」这类句子 guard 全部 passed=True、violations=[]，
    # 当着客户的面报价而且完全无痕。
    # 计价口径也算报价：「每小时」「起步价」「定金」后面跟一个数就是在开价。
    # 2026-08-12 补——原来只认「收费/费用/律师费/报价/价格」这几个词，
    # 于是「首次咨询免费，之后每小时 800」在授权原话被抠掉后**整句放行**：
    # 剩下的「之后每小时 800」既没有费用词、也没有货币单位，两条规则都够不着。
    ("quote-fee", r"(收费|费用|律师费|代理费|咨询费|服务费|报价|价格|价位|"
                  r"起步价|封顶|定金|预付款?)[^。！？!?]{0,12}"
                  r"[\d〇零一二两三四五六七八九十百千万]"),
    ("quote-fee", r"每\s*(小时|次|件|个案|案|月)[^。！？!?]{0,4}"
                  r"[\d〇零一二两三四五六七八九十百千万]"),
    ("quote-fee", r"[\d〇零一二两三四五六七八九十百千万][\d〇零一二两三四五六七八九十百千万.,]*"
                  r"\s*(万元|万块|万|千元|千块|千|元|块钱|块)"),
    ("quote-fee", r"百分之[\d〇零一二两三四五六七八九十]+"),
    ("quote-fee", r"[〇零一二两三四五六七八九十\d]\s*成(的)?(费|佣|提成|收|律师费)"),
    ("quote-fee", r"(按|收|抽|提)\s*[〇零一二两三四五六七八九十\d]+\s*(个)?点"),
    # 打折同样是改价。原来写作 `(给你|可以|能)(便宜|优惠|打折|减免)`，
    # 要求两截**紧挨着**，于是「可以给您打三折」——中间隔了「给您」——整句漏过去，
    # 而这正是最典型的一句招揽话。折扣本身也补上：「打三折」单独出现照拦。
    ("quote-fee", r"(打|降到?|减到?)\s*[〇零一二两三四五六七八九十\d.]+\s*折"),
    ("quote-fee", r"(给你|给您|可以|能|帮你|帮您|我们|这边)[^。！？!?]{0,6}"
                  r"(便宜|优惠|打折|减免|少收|降价)"),
    # 「免费」也是报价——零也是一个价。抖音那套话术里满屏「电话咨询免费」
    # 「免费沟通」，它们此前一条都拦不住：规则只认带数字的金额，而
    # 承诺不收钱恰恰是最容易被客户拿来说事的一种价格承诺。
    # 说明白「谁来谈费用」是律师的事，AI 连「不要钱」都不该替所里许。
    ("quote-fee", r"(免费|不收费|不花钱|不要钱|白给|0元|零元)"),
    # 评价对方当事人或司法机关
    ("attack-party", r"对方.{0,8}(骗子|无赖|肯定输|没戏|理亏|坏)"),
    ("attack-court",
     r"(法官|法院|检察院|检察官|警察|公安|办案机关).{0,10}(不公|乱判|乱来|有问题|收钱|腐败|针对)"),
    # 催促客户做法律行为
    ("push-legal-act", r"(赶紧|尽快|马上|立刻)(去)?(签|认罪|认罚|转账|打款|交钱|撤诉|和解|承认)"),
    ("push-legal-act", r"(你|您)(应该|必须|得)(认罪|签了|先交钱|打款|撤诉)"),
    # AI 不得冒充律师身份给意见
    ("impersonate", r"(我作为(你们?的)?律师|以律师身份|我给你出具法律意见)"),
]

_COMPILED = [(name, re.compile(pat)) for name, pat in FORBIDDEN]


# 律所**书面授权**可以对客说出口的原话（`Settings.approved_claims`）。
#
# 2026-08-12，律所方明确要求主打「免费法律咨询」，并在我两次提出
# 《律师业务推广行为规则》第十条的顾虑后重申「你不要管，按我说的做」。
# 这是律所的执业判断，由律所承担；我把它记录在案并照办。
#
# **但不是把费用闸门拆掉。** 拆掉的后果是模型可以自己编出「打三折」
# 「代理费一万」——那是律所没授权、也不知情的话。做法是只放行
# 律所逐字定下的那几句：先把它们从待检文本里抠掉再跑规则，
# 于是**授权的那句能说，别的关于钱的说法一句也漏不过去**。
_MASK = "\x00"


def _mask_approved(text: str, settings=None) -> str:
    from responder.config import get_settings

    try:
        raw = (settings or get_settings()).approved_claims
    except Exception:
        return text
    for phrase in (p.strip() for p in raw.split("|")):
        if phrase:
            text = text.replace(phrase, _MASK)
    return text


def check(text: str, settings=None) -> list[str]:
    """返回命中的规则名列表，空列表 = 通过。

    `settings` 必须能显式传进来：话术是从**注入的**配置里取那句授权原话的
    （`templates.free_claim`），而这里若一律读全局配置，两边就能悄悄错开——
    结果是话术里写着一句配置 A 授权的话，闸门却拿配置 B 去比对，
    整段被当成报价丢掉。默认仍读全局，生产里两者本就是同一个对象。
    """
    masked = _mask_approved(text, settings)
    return [name for name, pat in _COMPILED if pat.search(masked)]
